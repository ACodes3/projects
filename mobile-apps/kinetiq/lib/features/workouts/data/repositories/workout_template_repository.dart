import 'package:drift/drift.dart';

import 'package:kinetiq/core/database/app_database.dart';

/// Handles SQLite operations for reusable workout templates.
///
/// This repository contains database logic only.
/// UI widgets should not execute database queries directly.
class WorkoutTemplateRepository {
  const WorkoutTemplateRepository(this._database);

  final AppDatabase _database;

  // ----------------------------------------------------------
  // READ ALL TEMPLATES
  // ----------------------------------------------------------

  /// Returns all workout templates, newest updated first.
  Future<List<WorkoutTemplate>> getAllTemplates() {
    return (_database.select(_database.workoutTemplates)..orderBy([
          (table) => OrderingTerm(
            expression: table.updatedAt,
            mode: OrderingMode.desc,
          ),
        ]))
        .get();
  }

  // ----------------------------------------------------------
  // WATCH TEMPLATES
  // ----------------------------------------------------------

  /// Automatically emits updated templates when data changes.
  ///
  /// Useful for Riverpod and reactive Flutter screens.
  Stream<List<WorkoutTemplate>> watchAllTemplates() {
    return (_database.select(_database.workoutTemplates)..orderBy([
          (table) => OrderingTerm(
            expression: table.updatedAt,
            mode: OrderingMode.desc,
          ),
        ]))
        .watch();
  }

  // ----------------------------------------------------------
  // READ SINGLE TEMPLATE
  // ----------------------------------------------------------

  /// Returns one template by ID, or null if it does not exist.
  Future<WorkoutTemplate?> getTemplateById(int id) {
    return (_database.select(
      _database.workoutTemplates,
    )..where((table) => table.id.equals(id))).getSingleOrNull();
  }

  // ----------------------------------------------------------
  // CREATE TEMPLATE
  // ----------------------------------------------------------

  /// Saves a new workout template.
  ///
  /// Returns the ID generated by SQLite.
  Future<int> createTemplate(WorkoutTemplatesCompanion template) {
    return _database.into(_database.workoutTemplates).insert(template);
  }

  // ----------------------------------------------------------
  // UPDATE TEMPLATE
  // ----------------------------------------------------------

  /// Updates an existing template while preserving its ID.
  ///
  /// Also refreshes the updatedAt timestamp.
  Future<bool> updateTemplate(WorkoutTemplate template) {
    final updatedTemplate = template.copyWith(updatedAt: DateTime.now());

    return _database
        .update(_database.workoutTemplates)
        .replace(updatedTemplate);
  }

  // ----------------------------------------------------------
  // DELETE TEMPLATE
  // ----------------------------------------------------------

  /// Deletes a workout template by its ID.
  ///
  /// Returns the number of rows deleted.
  Future<int> deleteTemplate(int id) {
    return (_database.delete(
      _database.workoutTemplates,
    )..where((table) => table.id.equals(id))).go();
  }
}
